package com.anysoftkeyboard.calque.preprocessor

import com.anysoftkeyboard.calque.data.models.CuratedLesson
import com.anysoftkeyboard.calque.linguistics.ScoredWordInfo
import com.anysoftkeyboard.calque.linguistics.SentenceLevel
import java.io.ByteArrayOutputStream
import java.io.File
import kotlin.io.path.createTempDirectory
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.doubleOrNull
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.longOrNull
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

class TatoebaPackBuilderTest {

    private val common =
        listOf("el", "gato", "come", "pan", "la", "casa", "grande", "de", "mi", "amigo")
    private val rare =
        listOf(
            "zorro",
            "ñandú",
            "pingüino",
            "jirafa",
            "cebra",
            "lémur",
            "okapi",
            "tapir",
            "yak",
            "gnu"
        )

    /** Common words rank 100, rare words 5000; "desconocida" is not in the dictionary. */
    private val lookup: (String) -> ScoredWordInfo? = { word ->
        when (word) {
            "desconocida" -> null
            in rare -> ScoredWordInfo(frequencyRank = 5000)
            else -> ScoredWordInfo(frequencyRank = 100)
        }
    }

    /** A sentence of [words] words of which the first [rareCount] are rare. */
    private fun sentence(words: Int, rareCount: Int = 0) =
        (rare.take(rareCount) + common.take(words - rareCount)).joinToString(" ") + "."

    private fun pair(id: Long, text: String) = TatoebaPair(id, id + 1_000_000, text, "English $id")

    /** [count] sentences of level 0 (5 common words: score 1.25). */
    private fun level0(count: Int, firstId: Long = 1) =
        (0 until count).map { pair(firstId + it, sentence(5)) }

    private fun build(
        pairs: List<TatoebaPair>,
        config: TatoebaPackConfig = TatoebaPackConfig(packSize = 5, packsPerLevel = 10),
        firstSequence: (Int) -> Int = { 0 },
    ) = TatoebaPackBuilder.build(pairs, lookup, firstSequence, config)

    private fun CuratedLessonRow.sentences(): List<JsonObject> =
        (Json.parseToJsonElement(contentJson).jsonObject["sentences"] as JsonArray).map {
            it.jsonObject
        }

    // ----- shape --------------------------------------------------------------------------------

    @Test
    fun build_cutsTheSentencesIntoFullPacksAndDropsTheRemainder() {
        val result = build(level0(23))

        assertEquals(4, result.lessons.size)
        assertTrue(result.lessons.all { it.sentences().size == 5 })
        assertEquals(20, result.lessons.sumOf { it.sentences().size })
        assertEquals(4, result.stats.packsPerLevel.getValue(SentenceLevel.LEVEL_0))
        assertEquals(23, result.stats.scoredPerLevel.getValue(SentenceLevel.LEVEL_0))
    }

    @Test
    fun build_fewerSentencesThanOnePackMakeNoLesson() {
        assertTrue(build(level0(4)).lessons.isEmpty())
    }

    @Test
    fun build_theContentIsReadableByTheAppsCuratedLessonParser() {
        val lesson = build(level0(5)).lessons.single()

        val parsed =
            CuratedLesson(
                    lesson.lessonId,
                    lesson.level,
                    lesson.sequenceOrder,
                    lesson.title,
                    lesson.targetConcept,
                    lesson.contentJson,
                )
                .parseSentences()

        assertEquals(5, parsed.size)
        assertEquals(sentence(5), parsed.first().sentenceEs)
        assertTrue(parsed.all { it.translationEn.startsWith("English ") })
        // The interlinear gloss is generated by the reader at runtime.
        assertTrue(parsed.all { it.interlinearGloss.isEmpty() })
    }

    @Test
    fun build_everySentenceKeepsItsTwoTatoebaIdsForAttribution() {
        val lesson = build(level0(5, firstId = 40)).lessons.single()

        val content = Json.parseToJsonElement(lesson.contentJson).jsonObject
        assertEquals("tatoeba", content.getValue("source").jsonPrimitive.content)
        val ids =
            lesson.sentences().map {
                it.getValue("tatoeba_spanish_id").jsonPrimitive.longOrNull to
                    it.getValue("tatoeba_english_id").jsonPrimitive.longOrNull
            }
        assertEquals((40L..44L).map { it to it + 1_000_000 }.toSet(), ids.toSet())
    }

    // ----- levels, ordering, identity ------------------------------------------------------------

    @Test
    fun build_putsEverySentenceInTheLevelTheScorerGivesIt() {
        val pairs =
            level0(5) +
                (0 until 5).map { pair(100L + it, sentence(10, rareCount = 3)) } + // 4.0 -> level 1
                (0 until 5).map { pair(200L + it, sentence(10, rareCount = 6)) } // 5.5 -> level 2

        val result = build(pairs)

        assertEquals(listOf(0, 1, 2), result.lessons.map { it.level })
        assertEquals(
            listOf("tatoeba_l0_001", "tatoeba_l1_001", "tatoeba_l2_001"),
            result.lessons.map { it.lessonId }
        )
    }

    @Test
    fun build_numbersEachLevelFromOneAndKeepsIdsUnique() {
        val result = build(level0(15))

        assertEquals(
            listOf("tatoeba_l0_001", "tatoeba_l0_002", "tatoeba_l0_003"),
            result.lessons.map { it.lessonId }
        )
        assertEquals(result.lessons.size, result.lessons.map { it.lessonId }.toSet().size)
    }

    @Test
    fun build_sequenceOrderContinuesAfterTheExistingLessonsOfTheLevel() {
        val pairs = level0(10) + (0 until 5).map { pair(100L + it, sentence(10, rareCount = 3)) }

        val result = build(pairs) { level -> if (level == 0) 6 else 0 }

        val byLevel = result.lessons.groupBy { it.level }
        assertEquals(listOf(7, 8), byLevel.getValue(0).map { it.sequenceOrder })
        assertEquals(listOf(1), byLevel.getValue(1).map { it.sequenceOrder })
    }

    @Test
    fun build_laterLessonsOfALevelAreNotEasierThanEarlierOnes() {
        // 5-word sentences with 0..3 rare words: scores 1.25 .. 3.5, all level 0 or 1 -> use level
        // 1.
        val pairs =
            (0 until 40).map { pair(it + 1L, sentence(10, rareCount = 2 + (it % 2))) } // 3.5 or 4.0
        val result = build(pairs, TatoebaPackConfig(packSize = 5, packsPerLevel = 8))

        val scores =
            result.lessons.map { lesson ->
                lesson.sentences().map { it.getValue("score").jsonPrimitive.doubleOrNull!! }
            }
        for ((earlier, later) in scores.zipWithNext()) {
            assertTrue(earlier.max() <= later.min())
        }
        assertEquals(8, result.lessons.size)
    }

    // ----- selection ----------------------------------------------------------------------------

    @Test
    fun build_limitsALevelToPacksPerLevelLessons() {
        val result = build(level0(100), TatoebaPackConfig(packSize = 5, packsPerLevel = 3))

        assertEquals(3, result.lessons.size)
        assertEquals(15, result.lessons.sumOf { it.sentences().size })
    }

    @Test
    fun build_selectionDoesNotJustTakeTheFirstSentences() {
        val pairs = level0(100)

        val chosen =
            build(pairs, TatoebaPackConfig(packSize = 5, packsPerLevel = 3))
                .lessons
                .flatMap { it.sentences() }
                .map { it.getValue("tatoeba_spanish_id").jsonPrimitive.longOrNull!! }
                .toSet()

        assertEquals(15, chosen.size)
        assertNotEquals((1L..15L).toSet(), chosen)
    }

    @Test
    fun build_isDeterministicAndIndependentOfTheInputOrder() {
        val pairs = level0(60) + (0 until 20).map { pair(500L + it, sentence(10, rareCount = 3)) }
        val config = TatoebaPackConfig(packSize = 5, packsPerLevel = 4)

        val first = build(pairs, config)
        val second = build(pairs.reversed(), config)
        val third = build(pairs.shuffled(java.util.Random(7)), config)

        assertEquals(first.lessons, second.lessons)
        assertEquals(first.lessons, third.lessons)
    }

    // ----- rejections ---------------------------------------------------------------------------

    @Test
    fun build_skipsSentencesWithAWordMissingFromTheDictionary() {
        val unknown = pair(900, "el gato come desconocida pan.")

        val result = build(level0(5) + unknown)

        assertEquals(1, result.stats.unresolvedWord)
        val ids =
            result.lessons.single().sentences().map {
                it.getValue("tatoeba_spanish_id").jsonPrimitive.longOrNull
            }
        assertTrue(900L !in ids)
    }

    @Test
    fun build_countsSentencesTheScorerDiscards() {
        val tooShort = pair(901, "el gato.")
        val tooHard = pair(902, sentence(10, rareCount = 9)) // 2.5 + 4.5 = 7.0 > 6.5

        val result = build(level0(5) + tooShort + tooHard)

        assertEquals(2, result.stats.discarded)
        assertEquals(7, result.stats.candidates)
        assertEquals(1, result.lessons.size)
    }

    @Test
    fun config_rejectsNonPositiveSizes() {
        assertThrows(IllegalArgumentException::class.java) { TatoebaPackConfig(packSize = 0) }
        assertThrows(IllegalArgumentException::class.java) { TatoebaPackConfig(packsPerLevel = 0) }
    }

    // ----- processor and pipeline ---------------------------------------------------------------

    private fun dictionaryRows(words: List<String>, rank: Int) =
        words.map { DictionaryRow(it, it, "noun", DictionaryGrammar.BASE, it, false, rank) }

    private fun poolBytes(pairs: List<TatoebaPair>): ByteArray =
        ByteArrayOutputStream().also { TatoebaCandidateFiles.writeGzipTsv(pairs, it) }.toByteArray()

    @Test
    fun processor_storesTheLessonsAfterTheCuratedOnesOfTheSameLevel() {
        SeedDatabase.open().use { db ->
            db.insertDictionaryBatch(dictionaryRows(common, rank = 100))
            db.insertCuratedLessonsBatch(
                listOf(
                    CuratedLessonRow(
                        "lvl0_01_x",
                        0,
                        3,
                        "Curated",
                        "concept",
                        """{"sentences":[]}"""
                    )
                )
            )
            val pool = java.util.zip.GZIPInputStream(poolBytes(level0(10)).inputStream())

            val inserted =
                TatoebaProcessor.processSentences(
                    pool,
                    db,
                    TatoebaPackConfig(packSize = 5, packsPerLevel = 10)
                )

            assertEquals(2, inserted)
            val lessons = db.queryCuratedLessons()
            assertEquals(
                listOf("lvl0_01_x", "tatoeba_l0_001", "tatoeba_l0_002"),
                lessons.map { it.lessonId }
            )
            assertEquals(listOf(3, 4, 5), lessons.map { it.sequenceOrder })
        }
    }

    @Test
    fun processor_skipsSentencesWhoseWordsAreNotInTheDictionary() {
        SeedDatabase.open().use { db ->
            db.insertDictionaryBatch(dictionaryRows(common.drop(1), rank = 100)) // no "el"

            val packs = TatoebaProcessor.processPairs(level0(10), db, TatoebaPackConfig(5, 10))

            assertEquals(10, packs.stats.unresolvedWord)
            assertTrue(db.queryCuratedLessons().isEmpty())
        }
    }

    @Test
    fun pipeline_buildsTatoebaLessonsFromAGzipPoolAfterTheCuratedLessons() {
        val dir = createTempDirectory("calque_tatoeba_pipeline").toFile()
        val dictionary =
            File(dir, "dictionary_seed.json").apply {
                writeText(
                    common.joinToString(prefix = "[", postfix = "]") {
                        """{"surface_form":"$it","lemma":"$it","pos":"noun",""" +
                            """"english_gloss":"$it","frequency_rank":100}"""
                    }
                )
            }
        val lessons =
            File(dir, "curated.json").apply {
                writeText(
                    """[{"lesson_id":"lvl0_01_x","level":0,"sequence_order":1,"title":"T",""" +
                        """"content":{"sentences":[]}}]"""
                )
            }
        val pool = File(dir, "pool.tsv.gz").apply { writeBytes(poolBytes(level0(10))) }
        val dbFile = File(dir, "seed.db")

        val summary =
            PreprocessorPipeline(
                    PipelineConfig(
                        dbFile = dbFile,
                        dictionarySeedFile = dictionary,
                        curatedLessonsFile = lessons,
                        tatoebaFile = pool,
                        tatoebaPacks = TatoebaPackConfig(packSize = 5, packsPerLevel = 10),
                    )
                )
                .execute()

        assertEquals(3, summary.curatedLessonRows)
        SeedDatabase.open("jdbc:sqlite:${dbFile.absolutePath}").use { db ->
            assertEquals(
                listOf("lvl0_01_x", "tatoeba_l0_001", "tatoeba_l0_002"),
                db.queryCuratedLessons().map { it.lessonId },
            )
        }
        dir.deleteRecursively()
    }
}
