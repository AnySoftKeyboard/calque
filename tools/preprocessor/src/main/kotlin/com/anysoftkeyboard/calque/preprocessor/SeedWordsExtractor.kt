package com.anysoftkeyboard.calque.preprocessor

import com.anysoftkeyboard.calque.linguistics.SentenceScorer
import java.io.InputStream
import java.io.OutputStream
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject

/**
 * Lists the Spanish words the curated seeds use, so the Kaikki subset can be told to include them
 * (`extract-kaikki --extra-words`) even when they are too rare for the frequency list. Without
 * that, a false-cognate lemma such as `constipado`, or a word of a curated lesson, would have no
 * dictionary row and could not be tapped in the reader.
 *
 * Words come from: every sentence of the curated lessons, the lemma, the real Spanish word and the
 * example sentence of every false cognate, and the surface form and lemma of the dictionary seed.
 */
object SeedWordsExtractor {
    private const val SENTENCES_KEY = "sentences"

    /** Collects the sorted, lowercased words of the three seed files. */
    fun collect(
        curatedLessons: InputStream,
        falseCognates: InputStream,
        dictionarySeed: InputStream,
    ): List<String> {
        val words = sortedSetOf<String>()
        for (lesson in objects(curatedLessons)) {
            val content = lesson["content"] as? JsonObject ?: continue
            for (sentence in (content[SENTENCES_KEY] as? JsonArray).orEmpty()) {
                words.addAll(tokens((sentence as? JsonObject)?.text("sentence_es")))
            }
        }
        for (seed in objects(falseCognates)) {
            words.addAll(tokens(seed.text("lemma")))
            words.addAll(tokens(seed.text("real_spanish_for_apparent")))
            words.addAll(tokens(seed.text("example_es")))
        }
        for (entry in objects(dictionarySeed)) {
            words.addAll(tokens(entry.text("surface_form")))
            words.addAll(tokens(entry.text("lemma")))
        }
        return words.toList()
    }

    /** Writes [words] one per line under a short comment header. */
    fun write(words: List<String>, output: OutputStream) {
        val text = buildString {
            append("# Words used by the curated seeds; generated by extract-seed-words.\n")
            words.forEach { append(it).append('\n') }
        }
        output.write(text.toByteArray(Charsets.UTF_8))
        output.flush()
    }

    private fun objects(input: InputStream): List<JsonObject> {
        val root: JsonElement =
            Json.parseToJsonElement(input.bufferedReader(Charsets.UTF_8).readText())
        return root.jsonArray.map { it.jsonObject }
    }

    private fun JsonObject.text(key: String): String? = (this[key] as? JsonPrimitive)?.contentOrNull

    private fun tokens(text: String?): List<String> =
        if (text.isNullOrBlank()) {
            emptyList()
        } else {
            SentenceScorer.tokenizeWords(text).map { KaikkiSubsetExtractor.normalize(it) }
        }
}
